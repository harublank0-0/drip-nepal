import vine from '@vinejs/vine'
import { ADDRESS_LIMITS } from '#shared/constants/limits'
import { nepalMobile } from '#validators/support/nepal_mobile'
import { nfcText } from '#validators/support/nfc_text'

/*
 * The address book writes (docs/06 §13.4 `createAddress`, `updateAddress`;
 * 01 FR-IAM-012). The members are the whole input: anything else, `user_id`,
 * `postal_code`, `archived_at` or an encrypted column included, is refused
 * with `unknown_field` before this runs (`assertKnownMembers`, T-SEC-003).
 *
 * - `label`, `recipient_name`, `area_tole`, `street_landmark`: trimmed and
 *   in NFC, then counted in code points (`nfcText`, docs/04 §2.8), with the
 *   bounds of `ADDRESS_LIMITS`; `label` and `street_landmark` may be null,
 *   which leaves them empty (the JSON body parser reads `""` as null).
 * - `recipient_phone`: a Nepali mobile number, handed on in E.164
 *   (`nepalMobile`, AC-FR-IAM-012-3); a landline is refused.
 * - `province_code`, `district_code`, `local_level_code`: codes of the shape
 *   of docs/04a §9.1–§9.3; whether they exist and form one chain, and
 *   whether `ward_no` is within the local level's `ward_count`, is checked by
 *   the action against the reference data (`location_mismatch`,
 *   `ward_out_of_range`; AC-FR-IAM-012-1, -2). `postal_code` is generated by
 *   the database and never taken (04a §5.5).
 * - `ward_no`: a JSON integer from 1 to 40 (`user_addresses_ward_no_check`).
 * - `is_default`: a strict boolean.
 *
 * `updateAddress` takes the same members, each optional; the controller
 * refuses null or `""` for the ones that cannot be empty (`assertNotNull`),
 * because VineJS's `optional()` reads null as missing (vine 4.4).
 */
export const ADDRESS_MEMBERS = [
  'label',
  'recipient_name',
  'recipient_phone',
  'province_code',
  'district_code',
  'local_level_code',
  'ward_no',
  'area_tole',
  'street_landmark',
  'is_default',
] as const

// The members `updateAddress` may leave out but never send as null or `""`.
export const ADDRESS_NOT_NULL_MEMBERS = [
  'recipient_name',
  'recipient_phone',
  'province_code',
  'district_code',
  'local_level_code',
  'ward_no',
  'area_tole',
  'is_default',
] as const

const provinceCode = () => vine.string().regex(/^[1-7]$/)
const districtCode = () => vine.string().regex(/^[1-7]\d{2}$/)
const localLevelCode = () => vine.string().regex(/^[1-7]\d{4}$/)
const wardNo = () =>
  vine
    .number({ strict: true })
    .withoutDecimals()
    .range([ADDRESS_LIMITS.wardNo.min, ADDRESS_LIMITS.wardNo.max])

export const createAddressValidator = vine.create({
  label: nfcText(ADDRESS_LIMITS.label).nullable().optional(),
  recipient_name: nfcText(ADDRESS_LIMITS.recipientName),
  recipient_phone: nepalMobile(),
  province_code: provinceCode(),
  district_code: districtCode(),
  local_level_code: localLevelCode(),
  ward_no: wardNo(),
  area_tole: nfcText(ADDRESS_LIMITS.areaTole),
  street_landmark: nfcText(ADDRESS_LIMITS.streetLandmark).nullable().optional(),
  is_default: vine.boolean({ strict: true }).optional(),
})

export const updateAddressValidator = vine.create({
  label: nfcText(ADDRESS_LIMITS.label).nullable().optional(),
  recipient_name: nfcText(ADDRESS_LIMITS.recipientName).optional(),
  recipient_phone: nepalMobile().optional(),
  province_code: provinceCode().optional(),
  district_code: districtCode().optional(),
  local_level_code: localLevelCode().optional(),
  ward_no: wardNo().optional(),
  area_tole: nfcText(ADDRESS_LIMITS.areaTole).optional(),
  street_landmark: nfcText(ADDRESS_LIMITS.streetLandmark).nullable().optional(),
  is_default: vine.boolean({ strict: true }).optional(),
})
