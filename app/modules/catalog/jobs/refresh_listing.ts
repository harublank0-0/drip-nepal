import type { TransactionClientContract } from '@adonisjs/lucid/types/database'
import { jobTx } from '#modules/platform/tx'

/*
 * `catalog.refresh_listing` (docs/03 §9, docs/04a §7.12, ADR-0014; R1-S
 * parts 2a and 2e-i): recomputes one product's `product_listings` row from
 * the source tables. A product is visible when it is `published`, its shop
 * `active`, it has a `ready` image and an active variant; a visible product
 * gets its row (insert or replace), any other loses it. Each run rewrites
 * the whole row from what is committed, so duplicates and replays are
 * harmless (05 §4.7); a product that no longer exists leaves nothing to do.
 *
 * The row (04a §7.12):
 * - shop, product, category and brand copies, with `category_names` the
 *   names along the category's path, for search;
 * - `audience_value_ids`: the product's `audience` values;
 * - `size_value_ids` and `color_value_ids`: the values of the active
 *   variants that have stock to sell (`on_hand - reserved > 0`), so a size
 *   filter matches only products with that size in stock. Every variant
 *   attribute other than `color` is a size system (04 §3.8);
 * - prices over the active variants, and the compare-at price of the
 *   cheapest one;
 * - `in_stock`: any active variant with stock to sell;
 * - the primary image: the first `ready` image by position (every image a
 *   gallery holds is `ready`, `replaceProductMedia`), its derived keys, and
 *   its alt text, or "{title}, {colour}" with the colour it is linked to,
 *   or the title alone (04a §7.14, AC-FR-MED-002-2);
 * - `published_at`; `search_tsv` is generated by the table.
 *
 * The listing is catalog's read model, so it reads the other modules'
 * tables it summarises (shops, media, inventory) as source tables; it
 * writes only `product_listings`.
 */
export async function refreshProductListing(
  trx: TransactionClientContract,
  productId: string
): Promise<'listed' | 'not_visible' | 'no_product'> {
  const upserted = await trx.rawQuery(
    `WITH p AS (
       SELECT p.*, s.slug AS shop_slug, s.name AS shop_name, s.status AS shop_status
         FROM products p JOIN shops s ON s.id = p.shop_id
        WHERE p.id = :id
     ),
     v AS (
       SELECT v.id, v.price_minor, v.compare_at_price_minor,
              coalesce(i.on_hand - i.reserved, 0) > 0 AS available
         FROM product_variants v
         LEFT JOIN inventory_items i ON i.variant_id = v.id
        WHERE v.product_id = :id AND v.status = 'active'
     ),
     img AS (
       SELECT m.alt_text, a.derived_keys, cv.label AS colour_label
         FROM product_media m
         JOIN media_assets a ON a.id = m.media_asset_id AND a.status = 'ready'
         LEFT JOIN attribute_values cv ON cv.id = m.color_value_id
        WHERE m.product_id = :id
        ORDER BY m.position
        LIMIT 1
     ),
     visible AS (
       SELECT p.* FROM p
        WHERE p.status = 'published' AND p.shop_status = 'active'
          AND EXISTS (SELECT 1 FROM img) AND EXISTS (SELECT 1 FROM v)
     )
     INSERT INTO product_listings (
       product_id, shop_id, shop_slug, shop_name, public_id, slug, title,
       category_id, category_path, category_names, brand_id, brand_name, brand_slug,
       audience_value_ids, size_value_ids, color_value_ids,
       min_price_minor, max_price_minor, compare_at_price_minor, currency, in_stock,
       primary_image_keys, primary_image_alt, published_at, refreshed_at
     )
     SELECT
       p.id, p.shop_id, p.shop_slug, p.shop_name, p.public_id, p.slug, p.title,
       c.id, c.path,
       (SELECT string_agg(ancestor.name, ' ' ORDER BY ancestor.depth)
          FROM categories ancestor WHERE c.path LIKE ancestor.path || '%'),
       b.id, b.name, b.slug,
       ARRAY(SELECT pav.attribute_value_id
               FROM product_attribute_values pav
               JOIN attributes a ON a.id = pav.attribute_id
              WHERE pav.product_id = p.id AND a.code = 'audience'
              ORDER BY 1),
       ARRAY(SELECT DISTINCT o.attribute_value_id
               FROM variant_option_values o
               JOIN attributes a ON a.id = o.attribute_id
               JOIN v ON v.id = o.variant_id
              WHERE v.available AND a.scope = 'variant' AND a.code <> 'color'
              ORDER BY 1),
       ARRAY(SELECT DISTINCT o.attribute_value_id
               FROM variant_option_values o
               JOIN attributes a ON a.id = o.attribute_id
               JOIN v ON v.id = o.variant_id
              WHERE v.available AND a.code = 'color'
              ORDER BY 1),
       (SELECT min(v.price_minor) FROM v),
       (SELECT max(v.price_minor) FROM v),
       (SELECT v.compare_at_price_minor FROM v ORDER BY v.price_minor, v.id LIMIT 1),
       'NPR',
       EXISTS (SELECT 1 FROM v WHERE v.available),
       img.derived_keys,
       coalesce(
         img.alt_text,
         CASE WHEN img.colour_label IS NULL THEN p.title
              ELSE p.title || ', ' || img.colour_label END
       ),
       p.published_at,
       now()
       FROM visible p
       JOIN categories c ON c.id = p.category_id
       LEFT JOIN brands b ON b.id = p.brand_id
       CROSS JOIN img
     ON CONFLICT (product_id) DO UPDATE SET
       shop_id = EXCLUDED.shop_id, shop_slug = EXCLUDED.shop_slug,
       shop_name = EXCLUDED.shop_name, public_id = EXCLUDED.public_id,
       slug = EXCLUDED.slug, title = EXCLUDED.title,
       category_id = EXCLUDED.category_id, category_path = EXCLUDED.category_path,
       category_names = EXCLUDED.category_names, brand_id = EXCLUDED.brand_id,
       brand_name = EXCLUDED.brand_name, brand_slug = EXCLUDED.brand_slug,
       audience_value_ids = EXCLUDED.audience_value_ids,
       size_value_ids = EXCLUDED.size_value_ids,
       color_value_ids = EXCLUDED.color_value_ids,
       min_price_minor = EXCLUDED.min_price_minor,
       max_price_minor = EXCLUDED.max_price_minor,
       compare_at_price_minor = EXCLUDED.compare_at_price_minor,
       in_stock = EXCLUDED.in_stock,
       primary_image_keys = EXCLUDED.primary_image_keys,
       primary_image_alt = EXCLUDED.primary_image_alt,
       published_at = EXCLUDED.published_at,
       refreshed_at = now()
     RETURNING product_id`,
    { id: productId }
  )
  if (upserted.rows.length > 0) return 'listed'
  // Not visible (or gone): it has no row.
  await trx.from('product_listings').where('product_id', productId).delete()
  const exists = await trx.from('products').where('id', productId).select('id').first()
  return exists ? 'not_visible' : 'no_product'
}

export async function refreshListing(payload: { product_id: string }) {
  return jobTx(async (trx) => ({ outcome: await refreshProductListing(trx, payload.product_id) }))
}
